-- チームの色。個人ランキングなどでチームを背景色で示すために足す。
--
-- **NULL 許容**にする。本番には既にチームが入っているので、既存行を壊さずに
-- 追加できる形にする。色が未設定のチームは**ハイライトしない**（画面側で
-- 「色が無い＝壊れる」にしない）。
--
-- 形は #rrggbb の**小文字**だけを許す。
--   - 色は CSS に流れ込む値なので、名前より厳しく縛る。rgb() や var(--x)、
--     名前付き色（red）を通さない
--   - **大文字を落とすのは意図的**。GLOB は大文字小文字を区別するので、
--     '#FF0000' はここで弾かれる。保存形式が1つに揃っていないと、運営メニューの
--     「before と突き合わせて 409」が、同じ色なのに食い違って落ちる。
--     アプリ側は受け取った色を小文字に正規化してから書き込む。
--   - leagues の CHECK と同じ思想で、**運営が SQL を直接流したときの防衛線**にもなる
--
-- ★ 運営が SQL で直接書くときは **小文字で** 書くこと。
--    '#FF0000' は `CHECK constraint failed: teams` という読みにくいエラーになる。
--    正しくは '#ff0000'。アプリの運営メニューから設定する場合は自動で小文字に
--    直されるので、この注意が要るのは SQL を直に流すときだけ。
--
-- length() を併記するのは、GLOB のパターンが 7 文字ちょうどを強制するとはいえ、
-- 意図（7文字の #rrggbb）を読む側に見せるため。
ALTER TABLE teams ADD COLUMN color TEXT
  CHECK (
    color IS NULL
    OR (length(color) = 7
        AND color GLOB '#[0-9a-f][0-9a-f][0-9a-f][0-9a-f][0-9a-f][0-9a-f]')
  );
