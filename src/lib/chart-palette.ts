/**
 * 累計pt推移の線の色。
 *
 * ## 背景として良い色が、線として良いとは限らない
 *
 * 線は 2px の細さで**ほぼ白の背景**に引かれるので、明るい色は消える。実測:
 *
 *   #ffff00  白に対して 1.07:1  → ほとんど見えない（背景としては黒文字で 19.6:1）
 *   #f5f5dc  1.11:1             → 見えない
 *   #84cc16  1.98:1             → はっきり見える
 *   #0ea5e9  2.77:1             → はっきり見える
 *
 * **同じ色を名前の背景にも使う**ので、1色で両立させようとすると必ずどちらかが
 * 潰れる（T32 で山本さんが実際に踏んだ）。**選んだ色から線用の濃さを作る**方に
 * 変えたので（→ `lineColor`）、ここでは**もう「見えにくい色」が来ない**。
 *
 * 既定のパレット（個人モード用）はそのまま。メンバーは色を持たないので、
 * 派生させる元が無い。
 */

import { lineColor } from "./team-color";

/**
 * 個人モードは名簿の10人に加えて名簿外のメンバーが混じりうるので、
 * 10色だと先頭と末尾が同色になる。12色用意して1リーグ分は重ならないようにする。
 */
export const CHART_PALETTE = [
  "#0ea5e9",
  "#f43f5e",
  "#10b981",
  "#f59e0b",
  "#8b5cf6",
  "#14b8a6",
  "#ec4899",
  "#84cc16",
  "#6366f1",
  "#f97316",
  "#0891b2",
  "#a16207",
] as const;

/**
 * 系列の色を決める。
 *
 * `teamColors` は**チームモードのときだけ**渡す。個人モードに渡してはいけない
 * （メンバーは色を持たないので、チームから引くと同じチームの5人が全部同じ色になる）。
 * 未設定（null）のチームはパレットに落ちる。**片方だけ色を付けた状態**は
 * 普通に起きるので、そこで破綻させない。
 */
export function seriesColors(count: number, teamColors?: (string | null)[]): string[] {
  return Array.from({ length: count }, (_, i) => {
    const own = teamColors?.[i];
    // 選ばれた色をそのまま線にしない。薄い色は白地で消えるので、
    // 線として見える濃さに直してから使う（色相はそのまま）
    return own === undefined || own === null
      ? CHART_PALETTE[i % CHART_PALETTE.length]
      : lineColor(own);
  });
}
